import {cookies} from 'next/headers';
import {redirect} from 'next/navigation';
import {createServerClient} from '@supabase/ssr';
import Link from 'next/link';
import NotificationInbox from './NotificationInbox';
export const dynamic='force-dynamic';
export const metadata={title:'Landshop Internal Notifications'};
export default async function Notifications(){
 const url=process.env.NEXT_PUBLIC_SUPABASE_URL,key=process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
 if(!url||!key)return <main>Landshop notifications unavailable.</main>;
 const store=await cookies();
 const db=createServerClient(url,key,{
  cookieOptions:{domain:'.landshopnigeria.com',sameSite:'lax',path:'/',secure:true},
  cookies:{getAll(){return store.getAll()},setAll(changes){try{changes.forEach(v=>store.set(v.name,v.value,v.options))}catch{}}}
 });
 const {data:{user}}=await db.auth.getUser();
 if(!user)redirect('/staff/sign-in');
 const {data:verified,error:workError}=await db.rpc('landshop_staff_can_work',{p_user:user.id});
 if(workError||verified!==true)redirect('/staff');
 const r=await db.from('landshop_automation_inbox').select('id,subject,body,created_at,seen_at')
  .eq('user_id',user.id).order('created_at',{ascending:false}).limit(80);
 return <main style={{minHeight:'100vh',background:'#f0f8f4',padding:'clamp(16px,4vw,55px)',color:'#123e32'}}>
  <section style={{maxWidth:940,margin:'auto'}}>
   <Link href="/staff" style={{color:'#087d63',fontWeight:800}}>← Staff Dashboard</Link>
   <p style={{fontSize:11,color:'#d87520',letterSpacing:2,fontWeight:800,marginTop:25}}>LANDSHOP INTERNAL AUTOMATION</p>
   <h1 style={{fontSize:'clamp(30px,4vw,48px)',margin:'7px 0'}}>My Notifications</h1>
   <p style={{color:'#6d8679',lineHeight:1.7}}>These notices are generated by owner-approved internal workflows. External emails or WhatsApp messages are not assumed to have been sent.</p>
   {r.error&&<p role="alert">The notification service has not been activated yet.</p>}
   <NotificationInbox initial={r.data||[]}/>
  </section>
 </main>;
}
